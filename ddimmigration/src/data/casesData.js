/** 解析案例 date 字段（中文「YYYY年M月D日」）为可排序时间戳；无法解析时为 0 */
export function caseDateToTime(dateStr) {
  const m = String(dateStr || '').match(/(\d{4})年(\d{1,2})月(\d{1,2})日/)
  if (!m) return 0
  return new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3])).getTime()
}

